package tart

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestLauncherScript(t *testing.T) {
	s, err := launcherScript("/Users/admin/act/work", "/Users/admin/act/act/run/1.pgid", map[string]string{
		"B":                  "two words",
		"A":                  "it's",
		"INPUT_NODE-VERSION": "20",
		"UID":                "1",
	})
	require.NoError(t, err)
	assert.Equal(t, `# generated by act; removed when the step ends
cd /Users/admin/act/work || exit 1
ps -o pgid= -p $$ | tr -d ' ' > /Users/admin/act/act/run/1.pgid
A=it\'s; export A
B='two words'; export B
exec /usr/bin/env INPUT_NODE-VERSION=20 UID=1 "$@"
`, s)

	s, err = launcherScript("/w", "/p", nil)
	require.NoError(t, err)
	assert.Contains(t, s, "exec \"$@\"\n")

	_, err = launcherScript("/w", "/p", map[string]string{"A=B": "x"})
	assert.Error(t, err)
	_, err = launcherScript("/w", "/p", map[string]string{"A": "x\x00y"})
	assert.Error(t, err)
}

func TestResolveWorkdir(t *testing.T) {
	assert.Equal(t, "/ws", resolveWorkdir("/ws", ""))
	assert.Equal(t, "/ws/a/b", resolveWorkdir("/ws", "a/b"))
	assert.Equal(t, "/abs", resolveWorkdir("/ws", "/abs"))
}

