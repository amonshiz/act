package tart

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/kballard/go-shellquote"
)

// runDir is the directory under the act share that holds launchers and
// process-group files.
const runDir = "run"

var shellIdentifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// shellReadonly are variables that some /bin/sh implementations (bash in
// sh mode) make read-only; assigning them would abort the launcher, so they
// are passed through env(1) instead.
var shellReadonly = map[string]bool{"UID": true, "EUID": true, "PPID": true, "SHELLOPTS": true, "BASHOPTS": true, "BASH_VERSINFO": true}

// loginEnvSkip lists variables from the captured login environment that
// describe that one shell session and must not leak into steps.
var loginEnvSkip = map[string]bool{"PWD": true, "OLDPWD": true, "SHLVL": true, "_": true}

// filterLoginEnv drops session-specific variables from a login env.
func filterLoginEnv(env map[string]string) map[string]string {
	out := make(map[string]string, len(env))
	for k, v := range env {
		if loginEnvSkip[k] || strings.HasPrefix(k, "SSH_") {
			continue
		}
		out[k] = v
	}
	return out
}

// resolveWorkdir returns the guest directory a command runs in: the
// workspace when empty, joined to the workspace when relative.
func resolveWorkdir(workspace, workdir string) string {
	switch {
	case workdir == "":
		return workspace
	case strings.HasPrefix(workdir, "/"):
		return workdir
	default:
		return path.Join(workspace, workdir)
	}
}

func newExecID() string {
	b := make([]byte, 8)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

// launcher is one generated launcher script.
type launcher struct {
	hostPath  string // the script, on the host
	guestPath string // the script, in the guest
	pgidGuest string // where the script records its process group, in the guest
	pgidHost  string
}

func (l *launcher) cleanup() {
	_ = os.Remove(l.hostPath)
	_ = os.Remove(l.pgidHost)
}

// launcherScript renders the script. It changes to workdir, records its
// process group id in pgidFile so a cancel can kill the whole tree, exports
// every variable whose name is a shell identifier and passes the rest to
// env(1), then runs "$@". Values never appear on the command line.
func launcherScript(workdir, pgidFile string, env map[string]string) (string, error) {
	names := make([]string, 0, len(env))
	for k := range env {
		if k == "" || strings.ContainsAny(k, "=\x00") {
			return "", fmt.Errorf("invalid environment variable name %q", k)
		}
		if strings.ContainsRune(env[k], 0) {
			return "", fmt.Errorf("environment variable %s contains a NUL byte", k)
		}
		names = append(names, k)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("# generated by act; removed when the step ends\n")
	fmt.Fprintf(&b, "cd %s || exit 1\n", shellquote.Join(workdir))
	fmt.Fprintf(&b, "ps -o pgid= -p $$ | tr -d ' ' > %s\n", shellquote.Join(pgidFile))
	var rest []string
	for _, k := range names {
		if shellIdentifier.MatchString(k) && !shellReadonly[k] {
			fmt.Fprintf(&b, "%s=%s; export %s\n", k, shellquote.Join(env[k]), k)
		} else {
			rest = append(rest, shellquote.Join(k+"="+env[k]))
		}
	}
	if len(rest) == 0 {
		b.WriteString("exec \"$@\"\n")
	} else {
		fmt.Fprintf(&b, "exec /usr/bin/env %s \"$@\"\n", strings.Join(rest, " "))
	}
	return b.String(), nil
}

// writeLauncher writes a launcher into the host side of the act share.
// hostAct and guestAct are the two views of that directory.
func writeLauncher(hostAct, guestAct, workdir string, env map[string]string) (*launcher, error) {
	id := newExecID()
	pgidGuest := path.Join(guestAct, runDir, id+".pgid")
	script, err := launcherScript(workdir, pgidGuest, env)
	if err != nil {
		return nil, err
	}
	dir := filepath.Join(hostAct, runDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	l := &launcher{
		hostPath:  filepath.Join(dir, id+".sh"),
		guestPath: path.Join(guestAct, runDir, id+".sh"),
		pgidGuest: pgidGuest,
		pgidHost:  filepath.Join(dir, id+".pgid"),
	}
	if err := os.WriteFile(l.hostPath, []byte(script), 0o600); err != nil {
		return nil, err
	}
	return l, nil
}

// killScript terminates the process group a launcher recorded: SIGTERM,
// then SIGKILL after 5 seconds. It waits briefly for the pgid file in case
// the cancel races the launcher's start.
func killScript(pgidFile string) string {
	f := shellquote.Join(pgidFile)
	return `f=` + f + `; i=0
while [ ! -s "$f" ] && [ $i -lt 20 ]; do sleep 0.1; i=$((i+1)); done
p=$(tr -d ' \n' < "$f" 2>/dev/null)
case "$p" in ''|*[!0-9]*|0|1) exit 0;; esac
kill -TERM -- -"$p" 2>/dev/null || exit 0
i=0
while kill -0 -- -"$p" 2>/dev/null && [ $i -lt 50 ]; do sleep 0.1; i=$((i+1)); done
kill -KILL -- -"$p" 2>/dev/null
exit 0
`
}
